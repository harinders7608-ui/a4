      <span class="section-tag">Patron Guidance</span>
      <h2 class="section-title">Frequently Asked Inquiries</h2>
      <p class="section-lead">
        Essential knowledge regarding hide selection, bespoke customization, and leather longevity.
      </p>
    </div>
    <div class="faq-list">
      <div class="faq-item">
        <button class="faq-question">
          <span>What distinguishes full-grain crocodile-embossed leather from genuine exotic hide?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          Our bags are crafted from heavyweight European steer hide embossed under high-tonnage heat plates with master-sculpted crocodile scale topography. This provides the dramatic visual architecture of exotic scales combined with the superior tensile strength, abrasion resistance, and ethical sustainability of full-grain vegetable-tanned bovine leather.
        </div>
      </div>
      <div class="faq-item">
        <button class="faq-question">
          <span>How does traditional saddle stitching compare to machine lockstitching?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          Machine lockstitches use two threads that interlock in the middle of the hole; if a single thread wears through, the entire seam rapidly unravels. Our two-needle hand saddle stitch passes two independent waxed linen threads through each awl-pierced hole, forming a self-locking knot that remains secure even if an individual loop is severed.
        </div>
      </div>
      <div class="faq-item">
        <button class="faq-question">
          <span>What are the lead times for bespoke tote commissions?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          Because each tote is handcrafted start-to-finish by a single master artisan, bespoke commissions typically require between three to six weeks from initial leather selection and pattern scribing to final hot-iron edge burnishing and archival registration.
        </div>
      </div>
      <div class="faq-item">
        <button class="faq-question">
          <span>How should I maintain and condition the embossed leather surface?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          We advise applying a sparing coat of organic beeswax and neat's-foot oil leather balm once every four to six months using a horsehair dauber. Gently buff with a clean wool fleece cloth along the scale crevices. Avoid synthetic chemical sprays, petroleum distillates, or abrasive silicone cleaners.
        </div>
      </div>
      <div class="faq-item">
        <button class="faq-question">
          <span>Can I visit the 181 Mercer Street atelier in Manhattan?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          Yes. We welcome collectors and prospective patrons to our Mercer Street studio to inspect raw hide swatches, evaluate hardware finishes, and discuss custom monogramming. Private consultations are scheduled by appointment to ensure undivided artisan attention.
        </div>
      </div>
      <div class="faq-item">
        <button class="faq-question">
          <span>What warranty accompanies a CrocodileTote commission?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
